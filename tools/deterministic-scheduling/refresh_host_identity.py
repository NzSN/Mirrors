#!/usr/bin/env python3
"""Generate/check launcher-pinned host identities before compiling the DPM CLI."""
import sys
if __name__ == '__main__' and not (sys.flags.isolated and sys.flags.no_site and sys.dont_write_bytecode):
    print('DPM Python entrypoint requires python3 -I -S -B', file=sys.stderr)
    raise SystemExit(2)

import argparse
import hashlib
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
FILES = ['cli.py', 'dpm_host.py', 'timeline.py']


def refresh_helpers(check=False):
    for name, dependencies in [('install_cli.py', ['dpm_host']),
                               ('check_cli_installed.py', ['dpm_host', 'install_cli'])]:
        path = Path(__file__).with_name(name)
        pins = {dependency: hashlib.sha256(Path(__file__).with_name(dependency + '.py').read_bytes()).hexdigest()
                for dependency in dependencies}
        original = path.read_text()
        expected = re.sub(r'^_HELPER_SHA256 = .*  # refreshed helper identities$',
                          '_HELPER_SHA256 = ' + repr(pins) + '  # refreshed helper identities',
                          original, flags=re.MULTILINE)
        if original == expected:
            continue
        if check:
            raise SystemExit('DPM tool helper identities stale: ' + name)
        path.write_text(expected)


def content():
    interpreter = Path('/usr/bin/python3').resolve()
    rows = [(name, hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest()) for name in FILES]
    text = '-- Generated by tools/deterministic-scheduling/refresh_host_identity.py.\nnamespace Shell.Dpm.HostIdentity\n'
    text += 'def interpreter : String := "' + str(interpreter) + '"\n'
    text += 'def interpreterSha256 : String := "' + hashlib.sha256(interpreter.read_bytes()).hexdigest() + '"\n'
    text += 'def files : List (String × String) := [\n'
    text += ',\n'.join('  ("' + name + '", "' + digest + '")' for name, digest in rows) + ']\n'
    return text + 'end Shell.Dpm.HostIdentity\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); parser.add_argument('--helpers-only', action='store_true'); args=parser.parse_args()
    refresh_helpers(args.check)
    if args.helpers_only: raise SystemExit(0)
    destination=ROOT/'Shell/Dpm/HostIdentity.lean'; expected=content()
    if args.check:
        if not destination.exists() or destination.read_text()!=expected: raise SystemExit('DPM launcher identities stale; regenerate and rebuild')
    else: destination.write_text(expected)
