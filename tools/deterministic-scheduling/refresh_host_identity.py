#!/usr/bin/env python3
"""Generate/check launcher-pinned host identities before compiling the DPM CLI."""
import sys
if __name__ == '__main__' and not (sys.flags.isolated and sys.flags.no_site and sys.dont_write_bytecode):
    print('DPM Python entrypoint requires python3 -I -S -B', file=sys.stderr)
    raise SystemExit(2)

import argparse
import hashlib
import os
import re
import stat
import tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
TOOL_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT = ROOT / '.lake/build/dpm-generated/Shell/Dpm/HostIdentity.lean'
FILES = ['cli.py', 'dpm_host.py', 'timeline.py']


class PreparationError(Exception):
    pass


def write_if_changed(destination, expected):
    """Replace a complete generated file, preserving its timestamp on a no-op."""
    if destination.exists() and destination.read_text(encoding='utf-8') == expected:
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(destination.stat().st_mode) if destination.exists() else 0o644
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='',
                                         dir=destination.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write(expected)
        temporary.chmod(mode)
        os.replace(temporary, destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def refresh_helpers(check=False):
    # install_cli is a dependency of check_cli_installed: update in this order.
    for name, dependencies in [('install_cli.py', ['dpm_host']),
                               ('check_cli_installed.py', ['dpm_host', 'install_cli'])]:
        path = TOOL_DIR / name
        pins = {dependency: hashlib.sha256((TOOL_DIR / (dependency + '.py')).read_bytes()).hexdigest()
                for dependency in dependencies}
        original = path.read_text(encoding='utf-8')
        expected, count = re.subn(r'^_HELPER_SHA256 = .*  # refreshed helper identities$',
                                 '_HELPER_SHA256 = ' + repr(pins) + '  # refreshed helper identities',
                                 original, flags=re.MULTILINE)
        if count != 1:
            raise PreparationError('DPM tool helper identity declaration missing or duplicated: ' + name)
        if original == expected:
            continue
        if check:
            raise PreparationError('DPM tool helper identities stale: ' + name +
                                   '; run refresh_host_identity.py --helpers-only with python3 -I -S -B')
        write_if_changed(path, expected)


def lean_string(value):
    # Lean supports \uXXXX, but unlike JSON does not accept \b or \f escapes.
    escapes = {'"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
    return '"' + ''.join(escapes.get(char, '\\u%04x' % ord(char) if ord(char) < 32 or ord(char) == 127
                                   else char) for char in value) + '"'


def content():
    if not sys.executable:
        raise PreparationError('selected Python interpreter has no executable path')
    interpreter = Path(sys.executable).resolve(strict=True)
    rows = [(name, hashlib.sha256((TOOL_DIR / name).read_bytes()).hexdigest()) for name in FILES]
    text = '-- Generated by tools/deterministic-scheduling/refresh_host_identity.py.\nnamespace Shell.Dpm.HostIdentity\n'
    text += 'def interpreter : String := ' + lean_string(str(interpreter)) + '\n'
    text += 'def interpreterSha256 : String := "' + hashlib.sha256(interpreter.read_bytes()).hexdigest() + '"\n'
    text += 'def files : List (String × String) := [\n'
    text += ',\n'.join('  ("' + name + '", "' + digest + '")' for name, digest in rows) + ']\n'
    return text + 'end Shell.Dpm.HostIdentity\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify all selected identities without writing')
    parser.add_argument('--helpers-only', action='store_true', help='refresh only tracked helper pins (or verify with --check)')
    parser.add_argument('--check-helpers', action='store_true', help='verify tracked helper pins while generating the launcher identity')
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT, help='generated Lean module destination')
    args = parser.parse_args(argv)
    try:
        refresh_helpers(args.check or args.check_helpers)
        if args.helpers_only:
            return 0
        expected = content()
        if args.check:
            if not args.output.exists():
                raise PreparationError('DPM launcher identity missing: ' + str(args.output) +
                                       '; run lake build mirrors_dpm with the selected MIRRORS_DPM_PYTHON')
            if args.output.read_text(encoding='utf-8') != expected:
                raise PreparationError('DPM launcher identity stale: ' + str(args.output) +
                                       '; run lake build mirrors_dpm with the selected MIRRORS_DPM_PYTHON')
        else:
            write_if_changed(args.output, expected)
    except (PreparationError, OSError, UnicodeError) as error:
        print('DPM host identity preparation failed: ' + str(error), file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
